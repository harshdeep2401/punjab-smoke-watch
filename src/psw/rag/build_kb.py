"""Generate knowledge-base documents from our own processed data, with deterministic templates.

Every number in a generated doc is computed here from the parquet files or metrics.json. No LLM is used.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from psw import config
from psw.audit import gap
from psw.models import evaluate

NAAQS_24H = 60.0  # µg/m³, see the standards note
GEN_NOTE = "_Generated by the pipeline from processed data. Do not edit by hand._"


def _front(doc_id: str, title: str, doc_type: str, as_of: str, district: str | None = None, city: str | None = None,
           part: int | None = None) -> str:
    lines = [f"id: {doc_id}", f"title: {title}", f"doc_type: {doc_type}", f"as_of: {as_of}"]
    if part:
        lines.append(f"part: {part}")
    if district:
        lines.append(f"district: {district}")
    if city:
        lines.append(f"city: {city}")
    return "---\n" + "\n".join(lines) + "\n---\n"


def season_summary_doc(district: str, season: int, daily: pd.DataFrame) -> tuple[str, str]:
    """(doc_id, markdown) for one district and season. `daily` is district_daily for all districts and seasons."""
    d = daily[daily["season"] == season]
    totals = d.groupby("district").agg(n=("fire_count", "sum"), frp=("frp_sum", "sum"))
    ranked = totals["n"].rank(ascending=False, method="min").astype(int)
    mine = d[d["district"] == district]
    n, frp = int(mine["fire_count"].sum()), float(mine["frp_sum"].sum())
    peak = mine.loc[mine["fire_count"].idxmax()]
    rank, n_dist = int(ranked[district]), len(totals)

    prev = daily[(daily["season"] == season - 1) & (daily["district"] == district)]
    if len(prev):
        pn = int(prev["fire_count"].sum())
        change = (f"{(n - pn) / pn * 100:+.0f}% compared with {season - 1} ({pn:,} detections)" if pn > 0
                  else f"{season - 1} had no detections, so no percentage change is defined")
    else:
        change = f"no earlier season is available to compare with"

    doc_id = f"season_{season}_{district}"
    title = f"{district} fire season {season}"
    body = (
        f"# {district}: fire detections, season {season}\n\n"
        f"In the {season} season (Sep 15 to Nov 30), satellite fire detection (VIIRS S-NPP) recorded "
        f"{n:,} fire detections in {district} district, with a total fire radiative power of {frp:,.0f} MW. "
        f"Among the {n_dist} districts it ranked number {rank} by detections.\n\n"
        f"The busiest day was {peak['date']}, with {int(peak['fire_count'])} detections.\n\n"
        f"Compared with the previous season: {change}.\n\n"
        f"{GEN_NOTE} Detections are a lower bound (missed fires, cloud, overpass timing).\n"
    )
    return doc_id, _front(doc_id, title, "season_summary", f"{season}-12-01", district=district) + "\n" + body


def city_season_doc(city: str, season: int, pm25: pd.DataFrame) -> tuple[str, str]:
    """(doc_id, markdown) for one city and season, from daily CAMS PM2.5 inside the season window."""
    s = pm25[(pm25["city"] == city) & (pm25["date"] >= f"{season}-09-15") & (pm25["date"] <= f"{season}-11-30")]
    peak = s.loc[s["pm25_mean"].idxmax()]
    above = int((s["pm25_mean"] > NAAQS_24H).sum())
    doc_id = f"city_season_{season}_{city}"
    body = (
        f"# {city}: PM2.5, season {season}\n\n"
        f"From Sep 15 to Nov 30, {season}, the modelled (CAMS) daily mean PM2.5 in {city} averaged "
        f"{s['pm25_mean'].mean():.1f} µg/m³, with a maximum daily mean of {peak['pm25_mean']:.1f} µg/m³ on {peak['date']}. "
        f"{above} of {len(s)} days were above {NAAQS_24H:.0f} µg/m³ (the India NAAQS 24-hour level).\n\n"
        f"{GEN_NOTE} Values are modelled, not measured by a monitor.\n"
    )
    return doc_id, _front(doc_id, f"{city} PM2.5 season {season}", "city_season", f"{season}-12-01", city=city) + "\n" + body


def model_card_doc(metrics: dict) -> tuple[str, str]:
    """(doc_id, markdown) describing the backtest. as_of is the start of the first test season."""
    test = metrics["seasons_test"]
    v = {k: metrics["variants"][k]["overall"] for k in evaluate.VARIANTS}
    full, nof, per = v["full"], v["no_fire"], v["persistence"]
    folds = ", ".join(f"{s}: trained on {metrics['folds'][str(s)]}" for s in test)
    top = ", ".join(list(metrics["feature_importance"])[:6])

    def verdict(a: dict, b: dict, a_name: str, b_name: str) -> str:
        better = a["mae"] < b["mae"]
        return (f"{a_name} has a {'lower' if better else 'higher or equal'} MAE than {b_name} "
                f"({a['mae']:.2f} vs {b['mae']:.2f} µg/m³)")

    rows = "\n".join(f"| {k} | {v[k]['mae']:.2f} | {v[k]['pinball']:.2f} | {v[k]['coverage80']:.1%} | {v[k]['band_width']:.1f} |"
                     for k in evaluate.VARIANTS)
    fire_helps = full["mae"] < nof["mae"] and full["pinball"] < nof["pinball"]
    beats_persistence = full["mae"] < per["mae"]
    reading = (
        f"- Fire features {'improved' if fire_helps else 'did not improve'} the forecast: "
        f"{verdict(full, nof, 'the full model', 'the no-fire model')}.\n"
        f"- The model {'beat' if beats_persistence else 'did not beat'} the persistence baseline (tomorrow equals today): "
        f"{verdict(full, per, 'the full model', 'persistence')}.\n"
    )
    doc_id = "model_card"
    body = (
        f"# Model card: next-day PM2.5 forecast\n\n"
        f"The model is LightGBM quantile regression (p10, p50, p90) for the next-day mean PM2.5 in 4 cities. "
        f"Test seasons: {test}. Backtest folds ({folds}). Each fold uses only earlier seasons for training, "
        f"so the training sets are small (two to three seasons). Number of test rows per variant: {full['n']}.\n\n"
        f"Note on as_of: this card describes the method and the backtest result. Its date is the start of the first "
        f"test season so that briefings about the test seasons can cite it.\n\n"
        f"## Results on the test seasons\n\n"
        f"| variant | MAE (µg/m³) | pinball loss | 80% coverage | mean band width (µg/m³) |\n|---|---|---|---|---|\n{rows}\n\n"
        f"Variants: full = all features; no_fire = same model without fire features; persistence = tomorrow equals today.\n\n"
        f"## Reading\n\n{reading}\n"
        f"Possible reasons, not tested here: the CAMS model already includes fire emissions, "
        f"the training data is small, and a daily mean is a coarse target.\n\n"
        f"## Features\n\nThe features with the highest gain in the final model are: {top}. "
        f"The intervals were widened by a conformal correction measured on the last training season "
        f"(conformal applied: {metrics['conformal_applied']}).\n\n"
        f"{GEN_NOTE}\n"
    )
    first_test = f"{min(test)}-09-15"
    return doc_id, _front(doc_id, "Model card for the PM2.5 forecast", "model_card", first_test) + "\n" + body


# ---------- audit documents (Part 2) ----------

AUDIT_TABLES = ("sensor_trend", "night_share", "burned_vs_detected", "official_vs_satellite", "timing_indicators", "gap_range")
SENSOR_NAMES = {"snpp": "VIIRS S-NPP", "noaa20": "VIIRS NOAA-20", "noaa21": "VIIRS NOAA-21", "modis": "MODIS (Terra and Aqua)"}


def _change(pct, base: int) -> str:
    if pd.isna(pct):
        return f"no change against {base} can be computed"
    if round(pct, 1) == 0:
        return f"unchanged from {base}"
    return f"{'up' if pct > 0 else 'down'} {abs(pct):.1f}% from {base}"


def _pick(table: pd.DataFrame, district: str, season: int) -> pd.DataFrame:
    return table[(table["district"] == district) & (table["season"] == season)]


def _counts_section(district: str, season: int, t: dict[str, pd.DataFrame]) -> str:
    lines = []
    found = {r["sensor"]: r for r in _pick(t["sensor_trend"], district, season).to_dict("records")}
    base_counts = t["sensor_trend"][t["sensor_trend"]["district"] == district].set_index(["sensor", "season"])["count"]
    for r in (found[s] for s in SENSOR_NAMES if s in found):
        if r["base_season"] == season:
            change = "its first season"
        elif gap.small_base(base_counts[(r["sensor"], r["base_season"])]):
            change = f"too few in {r['base_season']} for a percentage change"
        else:
            change = _change(r["change_pct"], r["base_season"])
        lines.append(f"{SENSOR_NAMES[r['sensor']]} recorded {int(r['count']):,} detections ({change}).")
    night = _pick(t["night_share"], district, season)
    if not night.empty and night["total"].iloc[0] > 0:
        n = night.iloc[0]
        lines.append(f"Night passes gave {int(n['night']):,} of {int(n['total']):,} detections of all VIIRS satellites "
                     f"({n['night_share']:.1%}).")
    return "## Detections\n\n" + " ".join(lines)


def _other_signals_section(district: str, season: int, t: dict[str, pd.DataFrame]) -> str:
    lines = []
    bvd = _pick(t["burned_vs_detected"], district, season)
    if not bvd.empty:
        b = bvd.iloc[0]
        base = int(b["base_season"])
        change = "" if season == base else f", {_change(b['burned_change_pct'], base)}"
        lines.append(f"MODIS burned area (MCD64A1, low confidence in cropland) was {b['burned_km2']:,.0f} km²{change}.")
        if not pd.isna(b["detections_per_km2"]):
            lines.append(f"That is {b['detections_per_km2']:.2f} S-NPP detections per burned km².")
    off = _pick(t["official_vs_satellite"], district, season)
    if not off.empty:
        o = off.iloc[0]
        ratio = "" if pd.isna(o["ratio"]) else f", {o['ratio']:.2f} times the S-NPP count"
        lines.append(f"The official count, which is also satellite-based, was {int(o['official']):,}{ratio}.")
    return "## Other signals\n\n" + (" ".join(lines) or "No burned area or official count is available.")


def _gap_section(district: str, season: int, t: dict[str, pd.DataFrame]) -> str:
    row = _pick(t["gap_range"], district, season)
    if row.empty:
        return (f"## Detection gap\n\n{season} is the first season with data, so it is the base season and has no gap "
                "estimate.")
    g = row.iloc[0]
    if g["confidence"] == gap.INSUFFICIENT:
        return (f"## Detection gap\n\nInsufficient evidence for {district} in {season}: no range is given, because of "
                f"{g['reason']}.")
    return (f"## Detection gap\n\nThe gap (the fall in counts per burned km²; a negative value is a rise) is "
            f"{g['gap_low']:.0%} to {g['gap_high']:.0%} (confidence {g['confidence']}; {g['direction']}). "
            f"Methods: {gap.method_words(g['methods'])}.\n\n{gap.GAP_CAVEAT}")


def audit_doc(district: str, season: int, tables: dict[str, pd.DataFrame]) -> tuple[str, str]:
    """(doc_id, markdown) for one district (or "Punjab") and season, from the audit tables."""
    state = district == gap.STATE
    doc_id = f"audit_{season}_{'punjab' if state else district}"
    title = f"{district} burning audit, season {season}"
    # no "# title" line: every heading starts a chunk, and the title is already embedded with each chunk
    sections = [_counts_section(district, season, tables), _other_signals_section(district, season, tables),
                _gap_section(district, season, tables)]
    if state and not _pick(tables["gap_range"], district, season).empty:
        sections.append("## Timing indicators\n\n" + gap.timing_text(tables["timing_indicators"], season))
    sections.append(f"{GEN_NOTE} Season window Sep 15 to Nov 30.")
    front = _front(doc_id, title, "audit", f"{season}-12-01", district=None if state else district, part=2)
    return doc_id, front + "\n" + "\n\n".join(sections) + "\n"


def audit_docs(processed: Path) -> list[tuple[str, str]]:
    """Every audit document, or none if `pipeline audit` has not written its tables."""
    folder = Path(processed) / "audit"
    if not all((folder / f"{n}.parquet").exists() for n in AUDIT_TABLES):
        return []
    tables = {n: pd.read_parquet(folder / f"{n}.parquet") for n in AUDIT_TABLES}
    pairs = tables["burned_vs_detected"][["district", "season"]].drop_duplicates().sort_values(["season", "district"])
    return [audit_doc(d, int(s), tables) for d, s in pairs.itertuples(index=False)]


def generate_docs(processed: Path | None = None, out_dir: Path | None = None) -> list[Path]:
    """Write all generated docs to kb/generated and return the paths. Old generated files are removed first."""
    processed = Path(processed or config.PROCESSED)
    out_dir = Path(out_dir or config.KB / "generated")
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.md"):
        old.unlink()
    daily = pd.read_parquet(processed / "district_daily.parquet").assign(date=lambda d: d["date"].astype(str))
    pm25 = pd.read_parquet(processed / "pm25_daily.parquet").assign(date=lambda d: d["date"].astype(str))
    metrics = json.loads((processed / "metrics.json").read_text())
    docs = [season_summary_doc(dist, s, daily) for s in sorted(daily["season"].unique()) for dist in sorted(daily["district"].unique())]
    docs += [city_season_doc(c, s, pm25) for s in sorted(daily["season"].unique()) for c in sorted(pm25["city"].unique())]
    docs.append(model_card_doc(metrics))
    docs += audit_docs(processed)
    paths = []
    for doc_id, text in docs:
        p = out_dir / f"{doc_id}.md"
        p.write_text(text)
        paths.append(p)
    return paths
